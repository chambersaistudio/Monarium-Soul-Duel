#!/usr/bin/env node
'use strict';
const fs   = require('fs');
const path = require('path');

const charName    = process.argv[2] || 'flarepaw';
const publicChars = path.join(__dirname, '..', 'public', 'assets', 'characters');
const tsOutFile   = path.join(__dirname, '..', 'src', 'generated', 'flarepaw-manifest.ts');

const charDir = path.join(publicChars, charName);
if (!fs.existsSync(charDir)) {
  console.error(`[gen-manifest] Not found: ${charDir}`);
  process.exit(1);
}

function numericStem(filename) {
  const m = path.basename(filename, '.png').match(/\d+/);
  return m ? parseInt(m[0], 10) : 0;
}

const animations = {};
for (const entry of fs.readdirSync(charDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const folder     = entry.name;
  const folderPath = path.join(charDir, folder);
  const frames     = fs.readdirSync(folderPath)
    .filter(f => /\.png$/i.test(f))
    .sort((a, b) => numericStem(a) - numericStem(b))
    .map(f => path.basename(f, '.png'));
  if (frames.length > 0) animations[folder] = frames;
}

// ── TypeScript manifest (compile-time, imported by PreloadScene) ──────────────
const tsDir = path.dirname(tsOutFile);
if (!fs.existsSync(tsDir)) fs.mkdirSync(tsDir, { recursive: true });

const tsLines = [
  '// AUTO-GENERATED by tools/gen-manifest.js — do not edit by hand',
  '// npm run gen:manifest',
  '',
  `export const FLAREPAW_BASE = 'assets/characters/${charName}';`,
  '',
  'export const FLAREPAW_FRAMES: Record<string, readonly string[]> = {',
  ...Object.entries(animations).map(
    ([folder, stems]) => `  ${folder}: [${stems.map(s => `'${s}'`).join(', ')}],`,
  ),
  '};',
  '',
];

fs.writeFileSync(tsOutFile, tsLines.join('\n'));
console.log(`[gen-manifest] → ${tsOutFile}`);

// ── JSON manifest (runtime, loaded by browser via Phaser's JSON loader) ───────
const jsonOutFile = path.join(charDir, 'sprite-manifest.json');
const jsonData = {
  character: charName,
  generated: new Date().toISOString().slice(0, 10),
  animations,
};
fs.writeFileSync(jsonOutFile, JSON.stringify(jsonData, null, 2) + '\n');
console.log(`[gen-manifest] → ${jsonOutFile}`);

// ── Summary ───────────────────────────────────────────────────────────────────
console.log('');
for (const [folder, stems] of Object.entries(animations)) {
  console.log(`  ${folder}: ${stems.length} frames  [${stems.join(', ')}]`);
}
